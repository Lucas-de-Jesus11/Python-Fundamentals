#Operador and (e)
idade_Lucas = 21
idade_Pedro = 19
if (idade_Lucas >= 18) and (idade_Pedro >= 18):
    print('As dus condiçoes são verdadeiras!')

#Operador or (ou)
idade_Lucas = 21
idade_Pedro = 19
if (idade_Lucas >= 18) or (idade_Pedro >= 18):
    print('Pelo menos uma das condiçoes são verdadeiras!')

#Operador not (não)
idade_Lucas = 16
idade_Pedro = 19
if not(idade_Lucas >= 18):
    print('Invertir o valor')